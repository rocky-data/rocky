"""Helper for a Rocky child connector, written by `rocky connector init`.

Standard library only, Python 3.8 or newer. Parquet is written by the
standalone `duckdb` CLI, which must be on PATH.

A connector program calls `start()`, writes zero or more batches with
`Run.write()`, and ends with `Run.finish()`:

    import rocky_connector

    run = rocky_connector.start(state_schema_version=1)
    cursor = run.state.get("cursor") if run.state else None
    rows = [...]                      # a list of dicts, one per row
    if rows:
        run.write(rows)
    run.finish({"cursor": ...})       # the state Rocky saves for next run

Rocky starts the program once per `rocky load --connector <name>`. The
program reads one request on stdin, writes Parquet files into the request's
`output_dir`, and writes `_rocky_result.json` there. Rocky checks the files
and commits the state only after the load succeeds. Unknown request fields
are ignored, so a newer Rocky can add fields.

Do not edit this file: `rocky connector init` wrote it, and a newer Rocky
may ship a newer copy. Compare HELPER_VERSION with a fresh scaffold.
"""

import datetime
import decimal
import json
import os
import re
import subprocess
import sys

# The child connector protocol version this helper speaks.
PROTOCOL_VERSION = 0
# The version of this file. A newer Rocky may ship a newer one.
HELPER_VERSION = 1
RESULT_FILE = "_rocky_result.json"

_TYPE_PATTERN = re.compile(r"^[A-Za-z0-9_(), ]+$")


def log(message):
    """Write one line to stderr. Rocky logs it. Never log a secret."""
    print(message, file=sys.stderr, flush=True)


def fail(message):
    """Log `message` and exit 1. Rocky then retries or fails the load."""
    log("error: " + message)
    sys.exit(1)


def _literal(text):
    return "'" + text.replace("'", "''") + "'"


def _ident(name):
    return '"' + name.replace('"', '""') + '"'


def _json_value(value):
    # Values json cannot write. Anything else is refused rather than written
    # as its repr, which would load as the wrong text.
    if isinstance(value, (datetime.datetime, datetime.date, datetime.time)):
        return value.isoformat()
    if isinstance(value, decimal.Decimal):
        return str(value)
    raise TypeError(
        "cannot write a value of type %s; convert it to str, int, float, "
        "bool, None, a list or a dict" % type(value).__name__
    )


class Run:
    """One run of the connector: the request, the options and the state."""

    def __init__(self, request, state_schema_version):
        self.request = request
        self.run_id = request.get("run_id")
        self.output_dir = request["output_dir"]
        self.limits = request.get("limits") or {}
        self.state_schema_version = state_schema_version
        self.options = self._read_options()
        self.state = self._read_state()
        self._files = []
        self._columns = None

    def _read_options(self):
        # Rocky writes [connector.<name>.options] from rocky.toml to a JSON
        # file. It always exists, and holds {} when no option is set.
        path = self.request.get("options_path")
        if not isinstance(path, str) or not path:
            fail("the request has no options_path; this Rocky is too old")
        try:
            with open(path, encoding="utf-8") as handle:
                options = json.load(handle)
        except (OSError, ValueError) as error:
            fail("cannot read the options file: %s" % error)
        if not isinstance(options, dict):
            fail("the options file does not hold a JSON object")
        return options

    def _read_state(self):
        # None on the first run. Otherwise the value the last successful run
        # passed to finish().
        state = self.request.get("state")
        if state is None:
            return None
        found = state.get("schema_version")
        if found != self.state_schema_version:
            fail(
                "the saved state has schema version %r, but this connector "
                "reads %r" % (found, self.state_schema_version)
            )
        return state.get("value")

    def write(self, rows, columns=None):
        """Write `rows` (a list of dicts) as one Parquet file.

        `columns` is a dict of column name to DuckDB type, such as
        {"id": "BIGINT", "updated_at": "TIMESTAMP"}. With it, a row may leave
        out a column (it is written as NULL), but a row with a key that is not
        in `columns` stops the run, and so does a column no row in the batch
        has (usually a typo).

        Without `columns`, every row must have the same keys, and DuckDB
        infers each type from the rows. A column that is NULL in every row
        stops the run, because its type cannot be inferred. Inferred types
        depend on the data: text that looks like a date or a UUID can get
        another type in another run, and Rocky then refuses the load when
        the change is not a safe widening. Pass `columns` for a connector
        you run more than once.

        Every call in one run writes the columns and types of the first
        call, so the files share one schema. A later call that passes other
        `columns` stops the run.

        Values must be str, int, float, bool, None, lists or dicts.
        datetime, date and time values are written as ISO 8601 text and
        Decimal values as text; give their column a type in `columns`.
        bytes and NaN are refused. The rows are staged as JSON in
        `output_dir` while DuckDB converts them, and that file counts toward
        the connector's `output_bytes` limit. Write large sources in several
        calls.

        Returns the file name. An empty `rows` writes nothing and returns
        None.
        """
        if not rows:
            return None
        for number, row in enumerate(rows):
            if not isinstance(row, dict):
                fail("row %d is a %s, not a dict" % (number, type(row).__name__))
        if columns:
            for column, kind in columns.items():
                if not isinstance(kind, str) or not _TYPE_PATTERN.match(kind):
                    fail("the type %r of column %r is not a plain DuckDB type" % (kind, column))
            columns = dict((str(column), kind) for column, kind in columns.items())
            if self._columns is not None and columns != self._columns:
                fail(
                    "write() got the columns %r, but an earlier write() in this run "
                    "wrote %r" % (columns, self._columns)
                )
        typed = columns or self._columns
        if typed:
            keys = list(typed)
            expected = set(keys)
            seen = set()
            for number, row in enumerate(rows):
                extra = sorted(set(row) - expected)
                if extra:
                    fail("row %d has columns that are not in columns: %s" % (number, extra))
                seen.update(row)
            unseen = sorted(expected - seen)
            if unseen:
                fail("no row in this batch has the columns %s" % unseen)
        else:
            keys = list(rows[0])
            if not keys:
                fail("write() got rows with no columns")
            expected = set(keys)
            for number, row in enumerate(rows):
                if set(row) != expected:
                    fail(
                        "row %d does not have the columns of row 0: missing %s, extra %s "
                        "(pass columns to allow missing values)"
                        % (number, sorted(expected - set(row)), sorted(set(row) - expected))
                    )
            all_null = [key for key in keys if all(row[key] is None for row in rows)]
            if all_null:
                fail(
                    "the columns %s are NULL in every row, so their type cannot be "
                    "inferred; pass their types in columns" % all_null
                )
        index = len(self._files)
        name = "batch-%d.parquet" % index
        staging = os.path.join(self.output_dir, ".rows-%d.jsonl" % index)
        target = os.path.join(self.output_dir, name)
        reader = "read_json(%s, format = 'newline_delimited'" % _literal(staging)
        if typed:
            fields = ", ".join(
                "%s: %s" % (_literal(column), _literal(kind)) for column, kind in typed.items()
            )
            reader += ", columns = {%s}" % fields
        reader += ")"
        select = ", ".join(_ident(key) for key in keys)
        try:
            with open(staging, "w", encoding="utf-8") as handle:
                for row in rows:
                    ordered = dict((key, row.get(key)) for key in keys)
                    handle.write(json.dumps(ordered, default=_json_value, allow_nan=False))
                    handle.write("\n")
        except (TypeError, ValueError) as error:
            os.remove(staging)
            fail(str(error))
        sql = "SET TimeZone = 'UTC';\nCOPY (SELECT %s FROM %s) TO %s (FORMAT parquet);\n" % (
            select,
            reader,
            _literal(target),
        )
        if not typed:
            # Read back the types DuckDB chose, so later calls write the same.
            sql += (
                "SELECT column_name, column_type FROM "
                "(DESCRIBE SELECT * FROM read_parquet(%s));\n" % _literal(target)
            )
        sql += "SELECT CAST(count(*) AS VARCHAR) AS n FROM read_parquet(%s);\n" % _literal(target)
        try:
            results = _duckdb(sql)
        finally:
            # Remove the staging file whether or not the write worked.
            if os.path.exists(staging):
                os.remove(staging)
        rows_written = int(results[-1][-1]["n"])
        if rows_written != len(rows):
            fail("wrote %d rows to %s, expected %d" % (rows_written, name, len(rows)))
        if typed:
            self._columns = dict(typed)
        else:
            if len(results) < 2:
                fail("duckdb did not report the column types of %s" % name)
            self._columns = dict((c["column_name"], c["column_type"]) for c in results[-2])
            if list(self._columns) != keys:
                fail("duckdb wrote the columns %s, expected %s" % (list(self._columns), keys))
        self._files.append(
            {"path": name, "bytes": os.path.getsize(target), "rows": rows_written}
        )
        return name

    def finish(self, state):
        """Write the result file. `state` is any JSON value; Rocky saves it.

        Call it once, last. Pass the state unchanged when no row was read:
        Rocky commits it either way.
        """
        result = {
            "protocol_version": PROTOCOL_VERSION,
            "files": self._files,
            "state": {"schema_version": self.state_schema_version, "value": state},
        }
        path = os.path.join(self.output_dir, RESULT_FILE)
        with open(path, "w", encoding="utf-8") as handle:
            json.dump(result, handle)
        log(
            "wrote %d file(s), %d row(s)"
            % (len(self._files), sum(f["rows"] for f in self._files))
        )


def _parse_results(stdout):
    # The CLI prints one JSON array per statement that returns rows.
    decoder = json.JSONDecoder()
    results = []
    index = 0
    while True:
        while index < len(stdout) and stdout[index].isspace():
            index += 1
        if index >= len(stdout):
            return results
        value, index = decoder.raw_decode(stdout, index)
        results.append(value)


def _duckdb(sql):
    try:
        done = subprocess.run(
            ["duckdb", "-json", "-bail"],
            input=sql,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            check=False,
        )
    except FileNotFoundError:
        fail("the duckdb CLI is not on PATH")
    if done.returncode != 0:
        for line in done.stderr.splitlines():
            log("duckdb: " + line)
        fail("duckdb exited with code %d" % done.returncode)
    try:
        results = _parse_results(done.stdout)
    except ValueError as error:
        fail("cannot parse the duckdb output: %s" % error)
    if not results or not results[-1]:
        fail("duckdb returned no row count")
    return results


def start(state_schema_version):
    """Read the request from stdin and return a `Run`.

    `state_schema_version` must equal `state_schema_version` in
    connector.toml. Exits with an error when the request is not one this
    helper can serve.
    """
    try:
        request = json.load(sys.stdin)
    except ValueError as error:
        fail("the request on stdin is not JSON: %s" % error)
    if not isinstance(request, dict):
        fail("the request on stdin is not a JSON object")
    if request.get("protocol_version") != PROTOCOL_VERSION:
        fail(
            "the request speaks protocol %r, but this helper speaks %d"
            % (request.get("protocol_version"), PROTOCOL_VERSION)
        )
    output_dir = request.get("output_dir")
    if not isinstance(output_dir, str) or not os.path.isdir(output_dir):
        fail("the request has no usable output_dir")
    return Run(request, state_schema_version)
