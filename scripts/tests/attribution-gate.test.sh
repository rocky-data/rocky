#!/usr/bin/env bash
#
# Pin the decision logic behind .github/workflows/attribution-gate.yml: a PR
# whose title, body or commit messages carry agent attribution or an agent
# session link fails; ordinary text passes. Exercises scripts/attribution_gate.sh
# directly, since a PR-triggered workflow cannot run locally.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
readonly SCRIPT_DIR
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
readonly REPO_ROOT
readonly UNDER_TEST="$REPO_ROOT/scripts/attribution_gate.sh"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# Fixture strings are assembled from pieces so this file does not itself
# trip a scan for attribution lines.
readonly C="Claude"
readonly c="claude"
readonly ROBOT=$'\U0001F916'

pass=0
run_case() {
    local name="$1" want="$2" title="$3" body="$4" commits="$5" got
    printf '%s\n' "$commits" > "$WORK/commits"
    set +e
    PR_TITLE="$title" PR_BODY="$body" COMMITS_FILE="$WORK/commits" \
        bash "$UNDER_TEST" > "$WORK/out" 2>&1
    got=$?
    set -e
    if [[ "$got" -ne "$want" ]]; then
        echo "FAIL: $name: want exit $want, got $got" >&2
        sed 's/^/    /' "$WORK/out" >&2
        exit 1
    fi
    pass=$((pass + 1))
}

clean_commit="docs: fix a typo in the playground README"

run_case "clean PR passes" 0 \
    "docs: fix a typo" "Fixes a typo.

Changelog: none - docs-only typo fix" "$clean_commit"

run_case "mentioning the tool by name passes" 0 \
    "docs: say agents may use ${C} Code" "Agents such as ${C} Code read AGENTS.md." "$clean_commit"

run_case "robot generated-with line in body fails" 1 \
    "docs: x" "Body.

${ROBOT} Generated with [${C} Code](https://${c}.com/${c}-code)" "$clean_commit"

run_case "generated-by footer in body fails" 1 \
    "docs: x" "Body.

---
_Generated by [${C} Code](https://${c}.ai/code)_" "$clean_commit"

run_case "bare session link in body fails" 1 \
    "docs: x" "See https://${c}.ai/code/session_0123abc for context." "$clean_commit"

run_case "session trailer in a commit fails" 1 \
    "docs: x" "Body." "docs: x

${C}-Session: https://${c}.ai/code/session_0123abc"

run_case "agent co-author trailer in a commit fails" 1 \
    "docs: x" "Body." "docs: x

Co-Authored-By: ${C} Opus <noreply@anthropic.com>"

run_case "link in the title fails" 1 \
    "docs: from https://${c}.ai/share/abc" "Body." "$clean_commit"

run_case "case does not matter" 1 \
    "docs: x" "generated WITH ${c} CODE" "$clean_commit"

run_case "generated-with a model name, no 'Code', fails" 1 \
    "docs: x" "Generated with ${C} Opus" "$clean_commit"

run_case "double space in generated-by fails" 1 \
    "docs: x" "Generated by  ${C} Code" "$clean_commit"

run_case "bare host with no slash fails" 1 \
    "docs: x" "See (${c}.ai) for details." "$clean_commit"

run_case "bare host at end of line fails" 1 \
    "docs: x" "Made on ${c}.ai" "$clean_commit"

run_case "a longer host that only starts with the name passes" 0 \
    "docs: x" "Hosted at ${c}.airport.example" "$clean_commit"

run_case "empty body passes" 0 "docs: x" "" "$clean_commit"

set +e
PR_TITLE="x" PR_BODY="y" COMMITS_FILE="$WORK/missing" bash "$UNDER_TEST" > /dev/null 2>&1
missing=$?
set -e
[[ "$missing" -eq 2 ]] || { echo "FAIL: missing COMMITS_FILE: want exit 2, got $missing" >&2; exit 1; }
pass=$((pass + 1))

echo "attribution-gate: all $pass cases passed"
