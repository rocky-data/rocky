"""B3a harness: which "this table is unchanged" signal makes a model skip safe?

Workload: TPC-H at a chosen scale factor (default SF1, 6M lineitem rows),
generated by DuckDB's built-in `tpch` extension. The sources get a
`_synced_at` column, like a Fivetran-loaded table. Four TPC-H queries
(Q1, Q3, Q5, Q10) are the downstream models.

For each mutation class the harness, inside one transaction:
  1. applies the mutation to the sources,
  2. recomputes every candidate signal on every source,
  3. recomputes every model's output and an exact output fingerprint,
  4. rolls back.

A signal allows an UNSAFE SKIP when, for some model, the signal is the same
on every source that model reads, yet the model's output changed.
A FALSE REBUILD is the reverse: the signal changed, the output did not
(a cost, never a correctness problem).

Usage:
    pip install duckdb pytz
    python harness.py [--sf 1] [--json results.json]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import platform
import tempfile
import time

import duckdb

SOURCES = ["lineitem", "orders", "customer", "nation", "region", "supplier"]
# Tables that carry a loader timestamp. Small dimension tables in real
# pipelines often have one too; TPC-H's `nation`/`region` stand in for
# reference tables that are loaded without one.
TS_TABLES = ["lineitem", "orders", "customer", "supplier"]

MODELS = {
    # TPC-H Q1, pricing summary report.
    "q1_pricing_summary": (
        ["lineitem"],
        """
        SELECT l_returnflag, l_linestatus,
               sum(l_quantity) AS sum_qty,
               sum(l_extendedprice) AS sum_base_price,
               sum(l_extendedprice * (1 - l_discount)) AS sum_disc_price,
               sum(l_extendedprice * (1 - l_discount) * (1 + l_tax)) AS sum_charge,
               avg(l_quantity) AS avg_qty, avg(l_extendedprice) AS avg_price,
               avg(l_discount) AS avg_disc, count(*) AS count_order
        FROM lineitem
        WHERE l_shipdate <= DATE '1998-12-01' - INTERVAL 90 DAY
        GROUP BY l_returnflag, l_linestatus
        """,
    ),
    # TPC-H Q3, shipping priority. No LIMIT: a LIMIT over tied sort keys
    # makes the output itself non-deterministic, which is a separate trap
    # (see the report).
    "q3_shipping_priority": (
        ["customer", "orders", "lineitem"],
        """
        SELECT l_orderkey, sum(l_extendedprice * (1 - l_discount)) AS revenue,
               o_orderdate, o_shippriority
        FROM customer, orders, lineitem
        WHERE c_mktsegment = 'BUILDING' AND c_custkey = o_custkey
          AND l_orderkey = o_orderkey
          AND o_orderdate < DATE '1995-03-15' AND l_shipdate > DATE '1995-03-15'
        GROUP BY l_orderkey, o_orderdate, o_shippriority
        """,
    ),
    # TPC-H Q5, local supplier volume.
    "q5_local_supplier_volume": (
        ["customer", "orders", "lineitem", "supplier", "nation", "region"],
        """
        SELECT n_name, sum(l_extendedprice * (1 - l_discount)) AS revenue
        FROM customer, orders, lineitem, supplier, nation, region
        WHERE c_custkey = o_custkey AND l_orderkey = o_orderkey
          AND l_suppkey = s_suppkey AND c_nationkey = s_nationkey
          AND s_nationkey = n_nationkey AND n_regionkey = r_regionkey
          AND r_name = 'ASIA'
          AND o_orderdate >= DATE '1994-01-01' AND o_orderdate < DATE '1995-01-01'
        GROUP BY n_name
        """,
    ),
    # TPC-H Q10, returned item reporting (no LIMIT, as for Q3).
    "q10_returned_items": (
        ["customer", "orders", "lineitem", "nation"],
        """
        SELECT c_custkey, c_name,
               sum(l_extendedprice * (1 - l_discount)) AS revenue,
               c_acctbal, n_name, c_address, c_phone, c_comment
        FROM customer, orders, lineitem, nation
        WHERE c_custkey = o_custkey AND l_orderkey = o_orderkey
          AND o_orderdate >= DATE '1993-10-01' AND o_orderdate < DATE '1994-01-01'
          AND l_returnflag = 'R' AND c_nationkey = n_nationkey
        GROUP BY c_custkey, c_name, c_acctbal, c_phone, n_name, c_address, c_comment
        """,
    ),
}

# Mutation classes. Each is a list of SQL statements run inside a
# transaction that is rolled back afterwards. They model real ways a source
# table changes between two runs. TPC-H order keys are sparse (8 of every
# 32 are used), so the filters use prime moduli: a round modulus such as
# 400 can miss every key.
BASE_TS = "TIMESTAMP '2026-01-01 00:00:00'"
MUTATIONS = {
    "M0_no_change": [],
    "M1_append_newer_ts": [
        # A normal sync: new orders with their lines, loaded after every
        # existing row.
        """INSERT INTO orders SELECT * REPLACE (o_orderkey + 100000000 AS o_orderkey,
               _synced_at + INTERVAL 400 DAY AS _synced_at)
           FROM orders WHERE o_orderkey % 1009 = 7""",
        """INSERT INTO lineitem SELECT * REPLACE (l_orderkey + 100000000 AS l_orderkey,
               _synced_at + INTERVAL 400 DAY AS _synced_at)
           FROM lineitem WHERE l_orderkey % 1009 = 7""",
    ],
    "M1b_append_subsecond_newer_ts": [
        # A normal sync whose rows land under one second after the previous
        # max loader timestamp (a high-frequency loader, or a batch that
        # straddles a second boundary).
        """INSERT INTO lineitem SELECT * REPLACE (l_orderkey + 400000000 AS l_orderkey,
               (SELECT max(_synced_at) FROM lineitem) + INTERVAL 500 MILLISECOND AS _synced_at)
           FROM lineitem WHERE l_orderkey % 1009 = 7""",
    ],
    "M2_update_in_place_ts_kept": [
        # A correction written without touching the loader timestamp: a
        # manual UPDATE, a re-sync that preserves `_synced_at`, a vendor
        # backfill. Count and MAX(ts) do not move.
        "UPDATE lineitem SET l_discount = l_discount + 0.01 WHERE l_orderkey % 503 = 3",
    ],
    "M3_update_ts_bumped": [
        # A CDC-style update that bumps the loader timestamp.
        f"""UPDATE lineitem SET l_discount = l_discount + 0.01,
                   _synced_at = {BASE_TS} + INTERVAL 500 DAY
            WHERE l_orderkey % 503 = 3""",
    ],
    "M4_hard_delete": [
        # Rows deleted at the source and propagated as hard deletes.
        "DELETE FROM lineitem WHERE l_orderkey % 401 = 11",
    ],
    "M5_delete_plus_late_insert_same_count": [
        # Some rows deleted, as many late-arriving rows inserted with an
        # older loader timestamp. Count and MAX(ts) both unchanged.
        "CREATE TEMP TABLE _victims AS SELECT * FROM lineitem WHERE l_orderkey % 997 = 5",
        "DELETE FROM lineitem WHERE l_orderkey % 997 = 5",
        """INSERT INTO lineitem SELECT * REPLACE (l_orderkey + 200000000 AS l_orderkey,
               l_extendedprice * 2 AS l_extendedprice) FROM _victims""",
    ],
    "M6_late_arrival_older_ts": [
        # Late-arriving rows with a loader timestamp below the current max.
        """INSERT INTO lineitem SELECT * REPLACE (l_orderkey + 300000000 AS l_orderkey,
               {BASE_TS} AS _synced_at) FROM lineitem WHERE l_orderkey % 2003 = 9""".replace(
            "{BASE_TS}", BASE_TS
        ),
    ],
    "M7_noop_physical_rewrite": [
        # Same rows, rewritten in a new physical order (an OPTIMIZE, a
        # Z-ORDER, a CREATE OR REPLACE with the same data).
        "CREATE OR REPLACE TABLE lineitem AS SELECT * FROM lineitem ORDER BY hash(l_comment)",
    ],
    "M8_duplicate_row_pair": [
        # Two exact copies of an existing row appear (a double-delivered
        # batch). An XOR digest cancels the pair.
        "INSERT INTO lineitem SELECT * FROM lineitem WHERE l_orderkey = 1 AND l_linenumber = 1",
        "INSERT INTO lineitem SELECT * FROM lineitem WHERE l_orderkey = 1 AND l_linenumber = 1 LIMIT 1",
    ],
    "M9_swap_values_between_rows": [
        # Two rows trade one column value. Per-column sums do not move.
        """CREATE TEMP TABLE _swap AS SELECT l_orderkey, l_linenumber, l_extendedprice
           FROM lineitem WHERE (l_orderkey, l_linenumber) IN ((1, 1), (3, 1))""",
        """UPDATE lineitem SET l_extendedprice = (SELECT l_extendedprice FROM _swap
               WHERE l_orderkey = 3) WHERE l_orderkey = 1 AND l_linenumber = 1""",
        """UPDATE lineitem SET l_extendedprice = (SELECT l_extendedprice FROM _swap
               WHERE l_orderkey = 1) WHERE l_orderkey = 3 AND l_linenumber = 1""",
    ],
    "M10_type_widening": [
        # Schema drift: a DECIMAL column becomes DOUBLE, same values.
        "ALTER TABLE lineitem ALTER l_discount TYPE DOUBLE",
    ],
    "M11_dimension_update_no_ts": [
        # A reference table without a loader timestamp changes in place.
        "UPDATE nation SET n_name = 'CHINA (PRC)' WHERE n_name = 'CHINA'",
    ],
    "M12_dimension_update_ts_kept": [
        # A dimension with a loader timestamp, updated without bumping it.
        "UPDATE customer SET c_mktsegment = 'BUILDING' WHERE c_custkey % 50 = 1",
    ],
}


def ident_list(con, table):
    return [r[0] for r in con.execute(f"DESCRIBE {table}").fetchall()]


def signals(con, table, export_dir):
    """Every candidate signal for one table, plus the time each took."""
    out, cost = {}, {}
    has_ts = table in TS_TABLES
    cols = ident_list(con, table)
    row = "(" + ", ".join(cols) + ")"

    t = time.perf_counter()
    out["watermark"] = str(con.execute(f"SELECT max(_synced_at) FROM {table}").fetchone()[0]) if has_ts else None
    cost["watermark"] = time.perf_counter() - t

    t = time.perf_counter()
    out["row_count"] = con.execute(f"SELECT count(*) FROM {table}").fetchone()[0]
    cost["row_count"] = time.perf_counter() - t

    out["watermark_and_count"] = (out["watermark"], out["row_count"])

    # Rocky's shipped `--skip-unchanged` gate (skip_gate.rs, sig_unchanged):
    # MAX(ts) when the source has a tracked timestamp, else COUNT(*) only
    # with `skip_rowcount_fallback`, else "unprovable" (build). Compared by
    # `gate_unchanged` below, not by equality.
    raw_ts = con.execute(f"SELECT max(_synced_at) FROM {table}").fetchone()[0] if has_ts else None
    out["rocky_skip_gate"] = ("ts", raw_ts) if has_ts else ("unprovable", None)
    out["rocky_skip_gate_rowcount"] = ("ts", raw_ts) if has_ts else ("count", out["row_count"])
    cost["rocky_skip_gate"] = cost["watermark"]
    cost["rocky_skip_gate_rowcount"] = cost["watermark"] + (0 if has_ts else cost["row_count"])
    cost["watermark_and_count"] = cost["watermark"] + cost["row_count"]

    t = time.perf_counter()
    out["schema"] = con.execute(
        f"SELECT list(column_name || ':' || data_type ORDER BY ordinal_position) "
        f"FROM information_schema.columns WHERE table_name = '{table}'"
    ).fetchone()[0]
    cost["schema"] = time.perf_counter() - t

    # Per-column sums: a "checksum" some tools use.
    t = time.perf_counter()
    numeric = [
        c
        for c, ty in con.execute(
            f"SELECT column_name, data_type FROM information_schema.columns WHERE table_name = '{table}'"
        ).fetchall()
        if ty.startswith(("DECIMAL", "DOUBLE", "INTEGER", "BIGINT"))
    ]
    out["column_sums"] = (
        con.execute("SELECT " + ", ".join(f"sum({c})::VARCHAR" for c in numeric) + f" FROM {table}").fetchone()
        if numeric
        else None
    )
    cost["column_sums"] = time.perf_counter() - t

    # XOR of per-row hashes: the BigQuery `BIT_XOR(FARM_FINGERPRINT(...))` idiom.
    t = time.perf_counter()
    out["xor_row_hash"] = con.execute(f"SELECT bit_xor(hash({row})) FROM {table}").fetchone()[0]
    cost["xor_row_hash"] = time.perf_counter() - t

    # Multiset digest: count + two independent 64-bit sums of per-row
    # hashes (wrapping in HUGEINT, which cannot overflow at this size) +
    # the schema. Order-independent, duplicate-sensitive, one scan.
    t = time.perf_counter()
    c, s1, s2 = con.execute(
        f"SELECT count(*), sum(hash({row})::HUGEINT), sum(hash({row}, 'b3a-salt')::HUGEINT) FROM {table}"
    ).fetchone()
    out["multiset_digest"] = (c, str(s1), str(s2), tuple(out["schema"]))
    cost["multiset_digest"] = time.perf_counter() - t + cost["schema"]

    # Byte hash of a canonical export: what Rocky's Strong class records
    # for a table it wrote content-addressed. Here the export is written in
    # physical order, so it also shows how a byte hash reacts to a rewrite.
    t = time.perf_counter()
    path = os.path.join(export_dir, f"{table}.parquet")
    con.execute(f"COPY {table} TO '{path}' (FORMAT parquet)")
    h = hashlib.blake2b(digest_size=32)
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    out["file_bytes_hash"] = h.hexdigest()
    cost["file_bytes_hash"] = time.perf_counter() - t
    return out, cost


def output_fingerprint(con, sql):
    """Exact, order-independent fingerprint of a model's output, plus its compute time."""
    t = time.perf_counter()
    con.execute(f"CREATE OR REPLACE TEMP TABLE _model_out AS {sql}")
    elapsed = time.perf_counter() - t
    rows = con.execute("SELECT * FROM _model_out").fetchall()
    types = [r[1] for r in con.execute("DESCRIBE _model_out").fetchall()]
    canon = sorted(repr(r) for r in rows)
    h = hashlib.sha256(("|".join(types) + "\n" + "\n".join(canon)).encode()).hexdigest()
    return h, len(rows), elapsed


def ducklake_commit_signal(con, table):
    """(table uuid, last snapshot that changed the table) on DuckLake.

    This is the analog of a Delta `(table id, version)` or an Iceberg
    `(table uuid, current-snapshot-id)` pair: a commit-level marker the
    table format keeps, read from metadata without scanning data.
    """
    tid, uuid = con.execute(
        "SELECT table_id, table_uuid::VARCHAR FROM __ducklake_metadata_lake.ducklake_table "
        f"WHERE table_name = '{table}' AND end_snapshot IS NULL"
    ).fetchone()
    # Matches the table id in every change kind. A view or schema with the
    # same numeric id would over-report change; this harness creates tables
    # only, so that cannot happen here.
    last = None
    for snap, changes in con.execute("SELECT snapshot_id, changes FROM lake.snapshots()").fetchall():
        for kind, vals in (changes or {}).items():
            if any(v == str(tid) or v == f"main.{table}" for v in vals):
                last = snap
    return (uuid, last)


def commit_phase(sf, base_db, export_dir):
    """Run every mutation, committed, against a fresh DuckLake copy of the sources."""
    con = duckdb.connect()
    con.execute("LOAD ducklake")
    con.execute(f"ATTACH '{base_db}' AS base (READ_ONLY)")
    results = {}
    for name, stmts in MUTATIONS.items():
        lake_dir = os.path.join(export_dir, "lake_" + name)
        os.makedirs(lake_dir)
        con.execute(
            f"ATTACH 'ducklake:{lake_dir}/meta.ducklake' AS lake (DATA_PATH '{lake_dir}/data/')"
        )
        con.execute("USE lake")
        for tb in SOURCES:
            con.execute(f"CREATE TABLE lake.{tb} AS SELECT * FROM base.{tb}")
        before = {tb: ducklake_commit_signal(con, tb) for tb in SOURCES}
        out_before = {m: output_fingerprint(con, sql)[0] for m, (_, sql) in MODELS.items()}
        error = None
        try:
            for st in stmts:
                con.execute(st)
        except duckdb.Error as e:  # a mutation the format does not support
            error = str(e).splitlines()[0][:160]
        after = {tb: ducklake_commit_signal(con, tb) for tb in SOURCES}
        out_after = {m: output_fingerprint(con, sql)[0] for m, (_, sql) in MODELS.items()}
        per_model = {}
        for m, (reads, _) in MODELS.items():
            oc = out_after[m] != out_before[m]
            sc = any(after[tb] != before[tb] for tb in reads)
            per_model[m] = {
                "output_changed": oc,
                "verdict": "UNSAFE_SKIP" if oc and not sc else ("false_rebuild" if sc and not oc else "ok"),
            }
        results[name] = {"mutation_error": error, "models": per_model}
        print("commit-phase", name, error, {m: r["verdict"] for m, r in per_model.items()}, flush=True)
        con.execute("USE memory")
        con.execute("DETACH lake")
    unsafe = sorted(f"{mu}/{m}" for mu, r in results.items() for m, v in r["models"].items() if v["verdict"] == "UNSAFE_SKIP")
    false_rb = sorted(f"{mu}/{m}" for mu, r in results.items() for m, v in r["models"].items() if v["verdict"] == "false_rebuild")
    return {
        "unsafe_skips": len(unsafe),
        "unsafe_cases": unsafe,
        "false_rebuilds": len(false_rb),
        "false_rebuild_cases": false_rb,
        "results": results,
    }


def gate_unchanged(prev, cur):
    """The shipped gate's comparison, with `lag_tolerance_seconds = 0`.

    Mirrors `(cur_ts - prev_ts).num_seconds().unsigned_abs() <= 0`: chrono's
    `num_seconds` truncates toward zero, so a gap under one second counts as
    no movement.
    """
    if prev[0] == "ts" and cur[0] == "ts" and prev[1] is not None and cur[1] is not None:
        return int(abs((cur[1] - prev[1]).total_seconds())) <= 0
    if prev[0] == "count" and cur[0] == "count":
        return prev[1] == cur[1]
    return False


def changed_between(signal, prev, cur):
    if signal in ("rocky_skip_gate", "rocky_skip_gate_rowcount"):
        return not gate_unchanged(prev, cur)
    return prev != cur


SIGNALS = [
    "rocky_skip_gate",
    "rocky_skip_gate_rowcount",
    "watermark",
    "row_count",
    "watermark_and_count",
    "schema",
    "column_sums",
    "xor_row_hash",
    "multiset_digest",
    "file_bytes_hash",
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sf", type=float, default=1.0)
    ap.add_argument("--json", default=None)
    ap.add_argument("--only", default=None, help="comma-separated mutation names")
    ap.add_argument("--skip-commit-phase", action="store_true")
    args = ap.parse_args()

    tmp = tempfile.mkdtemp(prefix="b3a-")
    con = duckdb.connect(os.path.join(tmp, "tpch.duckdb"))
    t = time.perf_counter()
    con.execute(f"CALL dbgen(sf={args.sf})")
    gen = time.perf_counter() - t
    # Loader timestamps: one per order, spread over a year; lines inherit
    # their order's; customers and suppliers get one per row.
    con.execute(f"ALTER TABLE orders ADD COLUMN _synced_at TIMESTAMP")
    con.execute(f"UPDATE orders SET _synced_at = {BASE_TS} + to_seconds((o_orderkey * 7919) % 31536000)")
    con.execute(f"ALTER TABLE lineitem ADD COLUMN _synced_at TIMESTAMP")
    con.execute(
        f"UPDATE lineitem SET _synced_at = {BASE_TS} + to_seconds((l_orderkey * 7919) % 31536000)"
    )
    for tb, key in (("customer", "c_custkey"), ("supplier", "s_suppkey")):
        con.execute(f"ALTER TABLE {tb} ADD COLUMN _synced_at TIMESTAMP")
        con.execute(f"UPDATE {tb} SET _synced_at = {BASE_TS} + to_seconds(({key} * 104729) % 31536000)")
    con.execute("CHECKPOINT")
    sizes = {tb: con.execute(f"SELECT count(*) FROM {tb}").fetchone()[0] for tb in SOURCES}

    base_dir = os.path.join(tmp, "base")
    os.makedirs(base_dir)
    base_sig, base_cost = {}, {}
    for tb in SOURCES:
        base_sig[tb], base_cost[tb] = signals(con, tb, base_dir)
    base_out, model_cost = {}, {}
    for m, (_, sql) in MODELS.items():
        base_out[m], _, model_cost[m] = output_fingerprint(con, sql)

    selected = MUTATIONS if not args.only else {k: MUTATIONS[k] for k in args.only.split(",")}
    results = {}
    for name, stmts in selected.items():
        mdir = os.path.join(tmp, name)
        os.makedirs(mdir)
        con.execute("BEGIN TRANSACTION")
        for s in stmts:
            con.execute(s)
        sig = {tb: signals(con, tb, mdir)[0] for tb in SOURCES}
        outs = {m: output_fingerprint(con, sql)[0] for m, (_, sql) in MODELS.items()}
        con.execute("ROLLBACK")
        per_model = {}
        for m, (reads, _) in MODELS.items():
            out_changed = outs[m] != base_out[m]
            row = {"output_changed": out_changed, "signals": {}}
            for s in SIGNALS:
                # A signal that is undefined on a source (no timestamp
                # column) is treated as "unchanged" for that source: it
                # gives the skip no evidence either way.
                changed = any(changed_between(s, base_sig[tb][s], sig[tb][s]) for tb in reads)
                if out_changed and not changed:
                    verdict = "UNSAFE_SKIP"
                elif changed and not out_changed:
                    verdict = "false_rebuild"
                else:
                    verdict = "ok"
                row["signals"][s] = verdict
            per_model[m] = row
        results[name] = per_model
        print(name, {m: (r["output_changed"], [s for s, v in r["signals"].items() if v == "UNSAFE_SKIP"]) for m, r in per_model.items()}, flush=True)

    summary = {}
    for s in SIGNALS:
        unsafe = sorted({f"{mu}/{m}" for mu, pm in results.items() for m, r in pm.items() if r["signals"][s] == "UNSAFE_SKIP"})
        false_rb = sorted({f"{mu}/{m}" for mu, pm in results.items() for m, r in pm.items() if r["signals"][s] == "false_rebuild"})
        summary[s] = {
            "unsafe_skips": len(unsafe),
            "unsafe_cases": unsafe,
            "false_rebuilds": len(false_rb),
            "false_rebuild_cases": false_rb,
            "cost_seconds_all_sources": round(sum(base_cost[tb][s] for tb in SOURCES), 3),
        }
    commit = None
    if not args.skip_commit_phase:
        con.execute("CHECKPOINT")
        db_path = os.path.join(tmp, "tpch.duckdb")
        con.close()
        commit = commit_phase(args.sf, db_path, tmp)
    report = {
        "commit_version_signal": commit,
        "environment": {
            "duckdb": duckdb.__version__,
            "python": platform.python_version(),
            "machine": platform.machine(),
            "cpus": os.cpu_count(),
        },
        "scale_factor": args.sf,
        "dbgen_seconds": round(gen, 2),
        "source_rows": sizes,
        "model_compute_seconds": {m: round(v, 3) for m, v in model_cost.items()},
        "signal_cost_seconds": {tb: {s: round(v, 3) for s, v in c.items()} for tb, c in base_cost.items()},
        "summary": summary,
        "results": results,
    }
    print(json.dumps({"summary": summary, "model_compute_seconds": report["model_compute_seconds"]}, indent=2))
    if args.json:
        with open(args.json, "w") as fh:
            json.dump(report, fh, indent=2, sort_keys=True)


if __name__ == "__main__":
    main()
